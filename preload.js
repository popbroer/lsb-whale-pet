'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('whale', {
  init: () => ipcRenderer.invoke('whale:init'),
  save: (patch) => ipcRenderer.invoke('whale:save', patch),
  setIgnore: (ignore) => ipcRenderer.send('whale:setIgnore', ignore),
  getBounds: () => ipcRenderer.invoke('whale:getBounds'),
  move: (pos) => ipcRenderer.send('whale:move', pos),
  drop: () => ipcRenderer.send('whale:drop'),
  switchProvider: (payload) => ipcRenderer.invoke('whale:switch', payload),
  interact: (kind) => ipcRenderer.invoke('whale:interact', kind),
  getGrow: () => ipcRenderer.invoke('whale:grow'),
  getSkins: () => ipcRenderer.invoke('whale:skins'),
  setSkin: (id) => ipcRenderer.invoke('whale:skin:set', id),
  speak: (payload) => ipcRenderer.invoke('whale:speak', payload),
  getProfile: () => ipcRenderer.invoke('whale:profile'),
  tripStart: (destId) => ipcRenderer.invoke('whale:trip:start', destId),
  tripRecall: () => ipcRenderer.invoke('whale:trip:recall'),
  sendReply: (text) => ipcRenderer.invoke('whale:reply:send', text),
  replyStatus: () => ipcRenderer.invoke('whale:reply:status'),
  copy: (text) => ipcRenderer.invoke('whale:copy', text),
  openCC: () => ipcRenderer.send('whale:opencc'),
  menu: () => ipcRenderer.send('whale:menu'),
  quit: () => ipcRenderer.send('whale:quit'),

  onState: (cb) => ipcRenderer.on('whale:state', (_e, payload) => cb(payload)),
  onConfig: (cb) => ipcRenderer.on('whale:config', (_e, payload) => cb(payload)),
  onCommand: (cb) => ipcRenderer.on('whale:cmd', (_e, cmd) => cb(cmd)),
  onGrow: (cb) => ipcRenderer.on('whale:grow', (_e, g) => cb(g)),
  onLive: (cb) => ipcRenderer.on('whale:live', (_e, p) => cb(p)),
  onSkin: (cb) => ipcRenderer.on('whale:skin', (_e, s) => cb(s)),
  onApproval: (cb) => ipcRenderer.on('whale:approval', (_e, p) => cb(p)),
  onMeta: (cb) => ipcRenderer.on('whale:meta', (_e, p) => cb(p)),
  onTrip: (cb) => ipcRenderer.on('whale:trip', (_e, p) => cb(p)),
  onPostcard: (cb) => ipcRenderer.on('whale:postcard', (_e, p) => cb(p)),
  onAchievement: (cb) => ipcRenderer.on('whale:achievement', (_e, p) => cb(p)),
  onDish: (cb) => ipcRenderer.on('whale:dish', (_e, p) => cb(p)),
  onBudget: (cb) => ipcRenderer.on('whale:budget', (_e, p) => cb(p)),
  onRest: (cb) => ipcRenderer.on('whale:rest', (_e, p) => cb(p)),
  onGrowGain: (cb) => ipcRenderer.on('whale:grow-gain', (_e, p) => cb(p)),
  onLevelUp: (cb) => ipcRenderer.on('whale:levelup', (_e, p) => cb(p)),
});
